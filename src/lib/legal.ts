/** Splits the stored text into headings and paragraphs for rendering. */
export function legalBlocks(text: string) {
  return text.split(/\n\s*\n/).map((b) => b.trim()).filter(Boolean).flatMap((b) => {
    const lines = b.split('\n');
    return lines[0].startsWith('## ')
      ? [{ h: lines[0].slice(3).trim() }, ...(lines.length > 1 ? [{ p: lines.slice(1).join(' ').trim() }] : [])]
      : [{ p: b.replace(/\n/g, ' ') }];
  });
}
